import { IsPhone } from './phone.js';
import { PaymentMethod } from '@forgea/types';
import { Type } from 'class-transformer';
import {
  ArrayMaxSize,
  IsArray,
  IsBoolean,
  IsIn,
  IsInt,
  IsOptional,
  IsString,
  IsUUID,
  Matches,
  Max,
  MaxLength,
  Min,
  MinLength,
  ValidateIf,
  ValidateNested,
} from 'class-validator';
import { OptionSelectionDto } from './catalog.dto.js';
import { MONEY_PATTERN } from './constants.js';
import { Trim } from './email.js';
import { CART_QUANTITY_MAX } from './constants.js';
import { DesignMeasurementDto, TextDesignDto } from './text-studio.dto.js';

export class AddCartItemDto {
  @IsUUID()
  productId!: string;

  @IsOptional()
  @Type(() => Number)
  @IsInt()
  @Min(1)
  @Max(CART_QUANTITY_MAX)
  quantity: number = 1;

  /** The product's options as chosen; the API checks them against the product. */
  @IsArray()
  @ArrayMaxSize(20)
  @ValidateNested({ each: true })
  @Type(() => OptionSelectionDto)
  options: OptionSelectionDto[] = [];

  /** A personalised product: the customer's design (the API checks it and makes it). */
  @IsOptional()
  @ValidateNested()
  @Type(() => TextDesignDto)
  design?: TextDesignDto;

  /** The browser's measurement of that design (see DesignMeasurementDto). */
  @IsOptional()
  @ValidateNested()
  @Type(() => DesignMeasurementDto)
  measured?: DesignMeasurementDto;
}

export class UpdateCartItemDto {
  @Type(() => Number)
  @IsInt()
  @Min(1)
  @Max(CART_QUANTITY_MAX)
  quantity!: number;
}

/**
 * Checkout form. The customer is signed in (orders always belong to an account); name and
 * phone are remembered on the account for next time.
 */
export class CheckoutDto {
  /** Generated by the checkout page once per attempt; a repeated submit returns the same order. */
  @IsUUID()
  idempotencyKey!: string;

  @Trim()
  @IsString()
  @MinLength(2, { message: 'Enter your name' })
  @MaxLength(100)
  name!: string;

  @Trim()
  @IsPhone()
  phone!: string;

  @IsIn(Object.values(PaymentMethod))
  paymentMethod!: PaymentMethod;

  /** Currency the customer pays in (ISO code of an active currency). */
  @IsOptional()
  @Matches(/^[A-Z]{3}$/)
  currency: string = 'USD';

  /** false = pick up from the studio. */
  @IsBoolean()
  delivery!: boolean;

  @IsOptional()
  @IsBoolean()
  rush: boolean = false;

  @ValidateIf((o: CheckoutDto) => o.delivery)
  @Trim()
  @IsString()
  @MinLength(2, { message: 'Enter your city or area' })
  @MaxLength(100)
  city?: string;

  @ValidateIf((o: CheckoutDto) => o.delivery)
  @Trim()
  @IsString()
  @MinLength(5, { message: 'Enter a street, building and floor' })
  @MaxLength(300)
  addressLine?: string;

  @IsOptional()
  @Trim()
  @IsString()
  @MaxLength(500)
  deliveryNotes?: string;
}

/**
 * Accepting a custom request's quote: the order form, plus the price the customer saw. If the
 * studio re-quoted meanwhile, the acceptance is refused and the page shows the new price.
 */
export class AcceptQuoteDto extends CheckoutDto {
  @Matches(MONEY_PATTERN)
  quotedPrice!: string;
}
